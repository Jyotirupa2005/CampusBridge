CREATE DATABASE IF NOT EXISTS campusbridge CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE campusbridge;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 phone VARCHAR(25) DEFAULT NULL,
 password VARCHAR(255) NOT NULL,
 role ENUM('student','admin') NOT NULL DEFAULT 'student',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS applications (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 full_name VARCHAR(120) NOT NULL,
 dob DATE NOT NULL,
 gender VARCHAR(30) DEFAULT NULL,
 phone VARCHAR(25) NOT NULL,
 address TEXT NOT NULL,
 programme VARCHAR(150) NOT NULL,
 qualification VARCHAR(100) NOT NULL,
 percentage DECIMAL(5,2) NOT NULL,
 passing_year YEAR NOT NULL,
 document VARCHAR(255) DEFAULT NULL,
 status ENUM('Pending','Approved','Rejected') NOT NULL DEFAULT 'Pending',
 admin_note VARCHAR(500) DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_app_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_app_status(status), INDEX idx_app_user(user_id)
) ENGINE=InnoDB;
